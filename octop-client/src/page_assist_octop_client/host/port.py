from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable, Protocol


@dataclass
class HostUser:
    id: str
    display_name: str
    enabled: bool = True
    tenant_id: str = "default"


@dataclass
class RuntimeState:
    state: str = "idle"
    turn_id: str | None = None
    pending_id: str | None = None
    last_outcome: str | None = None

    def to_dict(self) -> dict[str, Any]:
        return {
            "state": self.state,
            "turn_id": self.turn_id,
            "pending_id": self.pending_id,
            "last_outcome": self.last_outcome,
        }


@dataclass
class TurnHandle:
    turn_id: str
    thread_id: str
    status: str
    events: list[dict[str, Any]] = field(default_factory=list)


class HostPort(Protocol):
    def get_state_root(self) -> Path: ...
    def get_instance_id(self) -> str: ...
    def get_host_build_id(self) -> str: ...
    def get_host_api_version(self) -> int: ...
    def is_ready(self) -> bool: ...
    def worker_count(self) -> int: ...
    def is_setup_complete(self) -> bool: ...
    def get_db_path(self) -> Path: ...
    def lookup_user(self, subject: str) -> HostUser | None: ...
    def authenticate_login(self, subject: str) -> HostUser: ...
    def check_acl(self, subject: str, expert_key: str, action: str) -> bool: ...
    def list_experts(self, subject: str, source: str, q: str | None) -> list[dict[str, Any]]: ...
    def get_expert_raw(self, expert_key: str) -> dict[str, Any] | None: ...

    def get_expert(self, expert_key: str) -> dict[str, Any] | None: ...
    def create_thread(self, subject: str, expert_key: str, request_id: str) -> dict[str, Any]: ...
    def get_thread(self, thread_id: str) -> dict[str, Any] | None: ...
    def list_threads(self, subject: str, expert_key: str) -> list[dict[str, Any]]: ...
    def get_history(self, thread_id: str, cursor: str | None) -> dict[str, Any]: ...
    def accept_turn(
        self,
        subject: str,
        expert_key: str,
        thread_id: str,
        client_request_id: str,
        question: str,
        context: dict[str, Any] | None,
        upload_ids: list[str],
    ) -> TurnHandle: ...
    def cancel_turn(self, thread_id: str, expected_turn_id: str) -> dict[str, Any]: ...
    def get_runtime(self, thread_id: str) -> RuntimeState: ...
    def store_upload(
        self,
        subject: str,
        expert_key: str,
        thread_id: str,
        filename: str,
        media_type: str,
        data: bytes,
        sha256: str,
    ) -> dict[str, Any]: ...
    def attach_uploads(self, thread_id: str, upload_ids: list[str]) -> None: ...
    def submit_approval(
        self,
        subject: str,
        expert_key: str,
        thread_id: str,
        pending_id: str,
        decision_id: str,
        decisions: list[dict[str, Any]],
    ) -> dict[str, Any]: ...
    def get_pending_approval(self, thread_id: str, pending_id: str) -> dict[str, Any] | None: ...
    def get_approval_instructions(self, thread_id: str, pending_id: str) -> dict[str, Any]: ...
    def bridge_kind(self, expert_key: str) -> str: ...
    def bridge_call(self, operation: str, payload: dict[str, Any]) -> dict[str, Any]: ...
    def mount_client_api(self, path: str, asgi_app: Callable) -> None: ...
    def register_auth_bypass(self, path_prefix: str) -> None: ...
    def on_start(self, callback: Callable[[], None]) -> None: ...
    def on_stop(self, callback: Callable[[], None]) -> None: ...
    def dashboard_binding_digest(self, expert_key: str) -> str: ...
